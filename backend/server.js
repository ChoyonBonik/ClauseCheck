require('dotenv').config();
const express = require('express');
const cors = require('cors');
const multer = require('multer');
const { GoogleGenerativeAI } = require('@google/generative-ai');

const app = express();
const port = process.env.PORT || 3000;

app.use(cors());
app.use(express.json({ limit: '50mb' }));

// Configure Multer for in-memory file handling
const storage = multer.memoryStorage();
const upload = multer({
  storage: storage,
  limits: { fileSize: 30 * 1024 * 1024 } // 30MB max
});

const apiKey = process.env.GEMINI_API_KEY;
if (!apiKey) {
  console.warn("⚠️ Warning: GEMINI_API_KEY environment variable is not set!");
}
const genAI = new GoogleGenerativeAI(apiKey || 'dummy_key');

// Contract Audit System Prompt
const SYSTEM_INSTRUCTION = `
You are an expert contract auditor and consumer protection legal analyst.
Your mission is to read contracts, policies, leases, or service agreements and identify predatory clauses, hidden traps, unfair liabilities, and missing protections.

You must respond strictly in JSON format matching this schema:
{
  "document_type": "string (e.g., Residential Lease, Freelance SOW, Employment Contract, Terms of Service)",
  "risk_score": integer (0 to 100, where 0 is completely safe, 100 is toxic/predatory),
  "verdict": "string ('Safe' | 'Moderate Risk' | 'High Risk' | 'Extreme Caution')",
  "executive_summary": [
    "string (bullet 1)",
    "string (bullet 2)",
    "string (bullet 3)"
  ],
  "red_flags": [
    {
      "title": "string (name of clause)",
      "quoted_text": "string (exact excerpt from document)",
      "risk_level": "string ('Critical' | 'Warning' | 'Caution')",
      "plain_english_explanation": "string (why this harms the user in simple terms)",
      "recommended_counter_action": "string (what to negotiate or request instead)"
    }
  ],
  "hidden_costs_or_penalties": [
    "string (e.g., $150 late fee after 2 days, auto-renewal with 60-day written notice)"
  ],
  "missing_protections": [
    "string (essential clauses missing that protect the user)"
  ],
  "disclaimer": "This analysis is generated by AI for informational purposes only and does not constitute formal legal advice."
}
`;

app.get('/health', (req, res) => {
  res.json({ status: 'ok', service: 'ClauseCheck API', model: 'gemini-3.5-flash' });
});

function detectMimeType(file) {
  let mime = file.mimetype;
  const originalName = file.originalname || '';
  const ext = originalName.split('.').pop().toLowerCase();

  if (ext === 'pdf') return 'application/pdf';
  if (ext === 'jpg' || ext === 'jpeg') return 'image/jpeg';
  if (ext === 'png') return 'image/png';
  if (ext === 'webp') return 'image/webp';
  if (ext === 'txt') return 'text/plain';

  // Check magic bytes if mime is octet-stream or missing
  if (!mime || mime === 'application/octet-stream') {
    if (file.buffer && file.buffer.length >= 4) {
      if (file.buffer.toString('ascii', 0, 4) === '%PDF') {
        return 'application/pdf';
      }
      if (file.buffer[0] === 0xFF && file.buffer[1] === 0xD8) {
        return 'image/jpeg';
      }
      if (file.buffer[0] === 0x89 && file.buffer[1] === 0x50 && file.buffer[2] === 0x4E && file.buffer[3] === 0x47) {
        return 'image/png';
      }
    }
    return 'application/pdf'; // Default fallback for documents
  }

  return mime;
}

// Main scan endpoint accepting PDF, images, or raw text
app.post('/api/scan', upload.array('files', 10), async (req, res) => {
  try {
    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({
        error: 'GEMINI_API_KEY is not configured on the server. Please check .env'
      });
    }

    const { contract_text, category } = req.body || {};
    const files = req.files || [];

    if (files.length === 0 && (!contract_text || contract_text.trim() === '')) {
      return res.status(400).json({
        error: 'Please upload at least one contract file (PDF/Image) or paste contract text.'
      });
    }

    const modelName = process.env.GEMINI_MODEL || 'gemini-3.5-flash';
    const model = genAI.getGenerativeModel({
      model: modelName,
      systemInstruction: SYSTEM_INSTRUCTION,
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.2
      }
    });

    const promptParts = [];

    // Add category context
    if (category) {
      promptParts.push({ text: `Document Category Focus: ${category}\n` });
    }

    // Add contract text if supplied
    if (contract_text && contract_text.trim() !== '') {
      promptParts.push({ text: `Contract Text Content:\n${contract_text}\n` });
    }

    // Add files (PDFs or images) directly to multimodal parts
    for (const file of files) {
      const mime = detectMimeType(file);
      console.log(`[Upload] Processing file: ${file.originalname || 'unnamed'}, detected mime: ${mime}, size: ${file.size} bytes`);
      promptParts.push({
        inlineData: {
          data: file.buffer.toString('base64'),
          mimeType: mime
        }
      });
    }

    console.log(`[Scan] Live AI Analysis requested: ${files.length} file(s), text length: ${contract_text ? contract_text.length : 0}`);

    const result = await model.generateContent(promptParts);
    const responseText = result.response.text();

    const parsedJson = JSON.parse(responseText);
    return res.json({
      success: true,
      timestamp: new Date().toISOString(),
      analysis: parsedJson
    });

  } catch (err) {
    console.error('[Scan Error]', err);
    return res.status(500).json({
      error: 'Failed to analyze contract with Gemini',
      details: err.message
    });
  }
});

// Interactive "Ask the Contract" Q&A Chat endpoint
app.post('/api/chat', async (req, res) => {
  try {
    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({ error: 'GEMINI_API_KEY is not configured on the server.' });
    }

    const { document_context, chat_history = [], message } = req.body || {};

    if (!message || message.trim() === '') {
      return res.status(400).json({ error: 'Message cannot be empty.' });
    }

    const modelName = process.env.GEMINI_MODEL || 'gemini-3.5-flash';
    const chatSystemInstruction = `
You are the ClauseCheck AI Legal Assistant. You are having an interactive conversation with a user about their contract/document.
You have been provided with the contract analysis context and clauses below:
---
${document_context || 'No specific document context provided.'}
---

Your Guidelines:
1. Answer the user's questions directly and accurately based on the contract context and general standard consumer protection practices.
2. If the contract explicitly covers the question, cite the clause or state what it says in plain, clear English.
3. If the contract does NOT mention what the user asks about (e.g. pets, subletting, grace period), clearly state that this document is silent on that issue and explain what risks or standard rights that implies.
4. Keep answers concise, actionable, and friendly. Avoid overly dense legal jargon.
5. Remind the user if a clause poses extreme risk or hidden liability.
`;

    const model = genAI.getGenerativeModel({
      model: modelName,
      systemInstruction: chatSystemInstruction,
      generationConfig: {
        temperature: 0.3,
      }
    });

    const contents = [];
    for (const h of chat_history) {
      contents.push({
        role: (h.role === 'assistant' || h.role === 'model') ? 'model' : 'user',
        parts: [{ text: h.text }]
      });
    }

    contents.push({
      role: 'user',
      parts: [{ text: message }]
    });

    console.log(`[Chat] Query: "${message.substring(0, 50)}..." (History length: ${chat_history.length})`);

    const result = await model.generateContent({ contents });
    const reply = result.response.text();

    return res.json({
      success: true,
      reply: reply
    });
  } catch (err) {
    console.error('[Chat Error]', err);
    return res.status(500).json({
      error: 'Failed to process chat message',
      details: err.message
    });
  }
});

app.listen(port, () => {
  console.log(`🚀 ClauseCheck Backend running on http://localhost:${port} using Gemini Live`);
});
