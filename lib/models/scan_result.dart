class RedFlag {
  final String title;
  final String quotedText;
  final String riskLevel; // 'Critical', 'Warning', 'Caution'
  final String plainEnglishExplanation;
  final String recommendedCounterAction;

  RedFlag({
    required this.title,
    required this.quotedText,
    required this.riskLevel,
    required this.plainEnglishExplanation,
    required this.recommendedCounterAction,
  });

  factory RedFlag.fromJson(Map<String, dynamic> json) {
    return RedFlag(
      title: json['title'] ?? 'Unspecified Clause',
      quotedText: json['quoted_text'] ?? '',
      riskLevel: json['risk_level'] ?? 'Warning',
      plainEnglishExplanation: json['plain_english_explanation'] ?? '',
      recommendedCounterAction: json['recommended_counter_action'] ?? '',
    );
  }

  Map<String, dynamic> toJson() => {
    'title': title,
    'quoted_text': quotedText,
    'risk_level': riskLevel,
    'plain_english_explanation': plainEnglishExplanation,
    'recommended_counter_action': recommendedCounterAction,
  };
}

class ScanResult {
  final String documentType;
  final int riskScore; // 0 to 100
  final String verdict;
  final List<String> executiveSummary;
  final List<RedFlag> redFlags;
  final List<String> hiddenCostsOrPenalties;
  final List<String> missingProtections;
  final String disclaimer;
  final DateTime scannedAt;

  ScanResult({
    required this.documentType,
    required this.riskScore,
    required this.verdict,
    required this.executiveSummary,
    required this.redFlags,
    required this.hiddenCostsOrPenalties,
    required this.missingProtections,
    required this.disclaimer,
    required this.scannedAt,
  });

  factory ScanResult.fromJson(Map<String, dynamic> json) {
    return ScanResult(
      documentType: json['document_type'] ?? 'General Contract',
      riskScore: (json['risk_score'] is int)
          ? json['risk_score']
          : int.tryParse(json['risk_score']?.toString() ?? '50') ?? 50,
      verdict: json['verdict'] ?? 'Moderate Risk',
      executiveSummary: (json['executive_summary'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      redFlags: (json['red_flags'] as List<dynamic>?)
              ?.map((e) => RedFlag.fromJson(e as Map<String, dynamic>))
              .toList() ??
          [],
      hiddenCostsOrPenalties: (json['hidden_costs_or_penalties'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      missingProtections: (json['missing_protections'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      disclaimer: json['disclaimer'] ??
          'This analysis is generated by AI for informational purposes only.',
      scannedAt: DateTime.now(),
    );
  }
}
